    // ──────────────────────────────────────────────────────────────
    // Z-SCORE CALCULATION
    // ──────────────────────────────────────────────────────────────
    public static function hitungZScore(float $nilai, int $umurBulan, string $jenisKelamin, string $tipe): ?float
    {
        $umur = min(60, max(0, $umurBulan));
        $ref  = match($tipe) {
            'weight' => $jenisKelamin === 'L' ? self::$whoWeightBoys : self::$whoWeightGirls,
            'height' => $jenisKelamin === 'L' ? self::$whoHeightBoys : self::$whoHeightGirls,
            default  => null,
        };
        if (!$ref) return null;

        // Nearest month
        $keys    = array_keys($ref);
        $closest = $keys[0];
        foreach ($keys as $k) {
            if (abs($k - $umur) < abs($closest - $umur)) $closest = $k;
        }
        [$m3sd, $m2sd, $median, $p2sd] = $ref[$closest];
        
        // m2sd is 2 standard deviations below the median.
        // Therefore, 1 SD is calculated by dividing the difference by 2.
        $sdBelow = ($median - $m2sd) / 2;
        $sdAbove = ($p2sd - $median) / 2;

        if ($nilai <= $median) {
            return $sdBelow > 0 ? round(($nilai - $median) / $sdBelow, 2) : 0;
        }
        return $sdAbove > 0 ? round(($nilai - $median) / $sdAbove, 2) : 0;
    }

    // ──────────────────────────────────────────────────────────────
    // WHO CLASSIFICATION: Normal | Stunting | Wasting | Underweight
    // ──────────────────────────────────────────────────────────────
    public static function hitungStatusGizi(float $beratBadan, int $umurBulan, string $jenisKelamin, float $tinggiBadan = 0): string
    {
        $waz = self::hitungZScore($beratBadan, $umurBulan, $jenisKelamin, 'weight');
        $haz = $tinggiBadan > 0
            ? self::hitungZScore($tinggiBadan, $umurBulan, $jenisKelamin, 'height')
            : null;

        if ($haz !== null && $haz < -2) return 'stunting';
        if ($waz !== null && $waz < -3) return 'wasting';
        if ($waz !== null && $waz < -2) return 'underweight';
        return 'normal';
    }

    // ──────────────────────────────────────────────────────────────
    // WHO REFERENCE CURVES FOR CHART
    // ──────────────────────────────────────────────────────────────
    public static function getWhoReferenceForChart(int $min, int $max, string $jenisKelamin, string $tipe, bool $perWeek = false): array
    {
        $ref = match($tipe) {
            'weight' => $jenisKelamin === 'L' ? self::$whoWeightBoys : self::$whoWeightGirls,
            'height' => $jenisKelamin === 'L' ? self::$whoHeightBoys : self::$whoHeightGirls,
            default  => [],
        };

        $labels = []; $m3 = []; $m2 = []; $med = []; $p2 = [];
        
        if ($perWeek) {
            for ($w = $min; $w <= $max; $w++) {
                $labels[] = $w . ' mgg';
                
                // Approximate 1 month = 4.34524 weeks
                $m = $w / 4.34524;
                $m_floor = (int) floor($m);
                $m_ceil = (int) ceil($m);
                if ($m_ceil > 60) $m_ceil = 60;
                if ($m_floor > 60) $m_floor = 60;
                
                $fraction = $m - $m_floor;
                
                $valFloor = $ref[$m_floor] ?? $ref[60];
                $valCeil = $ref[$m_ceil] ?? $ref[60];
                
                $m3[] = round($valFloor[0] + ($valCeil[0] - $valFloor[0]) * $fraction, 2);
                $m2[] = round($valFloor[1] + ($valCeil[1] - $valFloor[1]) * $fraction, 2);
                $med[] = round($valFloor[2] + ($valCeil[2] - $valFloor[2]) * $fraction, 2);
                $p2[] = round($valFloor[3] + ($valCeil[3] - $valFloor[3]) * $fraction, 2);
            }
        } else {
            foreach ($ref as $bulan => $vals) {
                if ($bulan >= $min && $bulan <= $max) {
                    $labels[] = $bulan . ' bln';
                    $m3[]  = $vals[0];
                    $m2[]  = $vals[1];
                    $med[] = $vals[2];
                    $p2[]  = $vals[3];
                }
            }
        }
        
        return compact('labels', 'm3', 'm2', 'med', 'p2', 'min', 'max');
    }
